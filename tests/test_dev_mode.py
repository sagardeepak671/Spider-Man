from harness import *
t = T("Dev mode + old saves")
with sync_playwright() as p:
    b, pg, errs = open_page(p)
    click(pg, '[data-action="toggle-dev"]')
    t.check(ev(pg, "game.devMode") is True, "dev mode on")
    t.check(ev(pg, "JSON.parse(localStorage.getItem('spiderman-game-settings')).dev") is True, "dev mode remembered")
    click(pg, '[data-action="campaign"]')
    t.check(ev(pg, "game.campaignWorldIndex") == 0, "dev mode does not jump to the last world")
    t.check(tile_status(pg) == ["1-1:PLAY", "1-2:DEV", "1-3:DEV", "1-4:DEV"], f"world 1 dev tiles {tile_status(pg)}")
    click(pg, '.spiderman-game-world-tab[data-world="1"]')
    tabs = ev(pg, "[...document.querySelectorAll('.spiderman-game-world-tab')].map(t=>t.className)")
    t.check("is-world-locked" not in tabs[1], "world 2 tab open in dev mode")
    t.check(tile_status(pg) == ["2-1:DEV", "2-2:DEV", "2-3:DEV", "2-4:DEV"], f"world 2 dev tiles {tile_status(pg)}")
    t.check("DEV MODE" in note(pg), "dev note")
    click(pg, '[data-level="2-1"]')
    t.check(state(pg) == "PLAYING" and ev(pg, "game.level.id") == "2-1", "2-1 playable in dev mode")
    ev(pg, "game.showMainMenu(); game.handleMenuAction('campaign')")
    t.check(ev(pg, "game.campaignWorldIndex") == 1, "level select returns to world 2")
    click(pg, '[data-level="2-4"]')
    t.check(state(pg) == "PLAYING" and ev(pg, "game.level.boss.bossName") == "GREEN GOBLIN", "dev mode: the goblin fight can be started")
    ev(pg, "game.showMainMenu(); game.handleMenuAction('campaign')")
    click(pg, '.spiderman-game-world-tab[data-world="1"]')
    # dev-mode clear of 2-1 is saved normally and shows the real unlock
    click(pg, '[data-level="2-1"]')
    ev(pg, "(() => { var s = game.spiderman; var g = game.level.goal; s.x = g.x - 30; s.y = g.y - s.bodyHeight() - 2; })()")
    pg.wait_for_timeout(400)
    t.check(state(pg) == "COMPLETE", "dev clear of 2-1")
    t.check(ev(pg, "game.isLevelCompleted('2-1')"), "dev clear saved")
    t.check(ev(pg, "document.querySelector('.spiderman-game-unlock-line').textContent") == "STAGE 2-2 UNLOCKED!", "unlock line in dev mode")
    # dev mode off: world 2 really locked again (1-4 not cleared), the 2-1 clear is kept
    ev(pg, "game.showMainMenu()")
    click(pg, '[data-action="toggle-dev"]')
    click(pg, '[data-action="campaign"]')
    t.check(ev(pg, "game.campaignWorldIndex") == 0, "dev off -> world 1")
    t.check(ev(pg, "game.isLevelUnlocked('2-1')") is False, "2-1 locked without dev mode (boss not beaten)")
    click(pg, '.spiderman-game-world-tab[data-world="1"]')
    st = tile_status(pg)
    t.check(st[0] == "2-1:LOCKED:L", f"locked tile wins over a dev clear {st}")
    b.close()

    # ---- save written by the previous version (World 1 fully cleared) ----
    b, pg, errs2 = open_page(p)
    old = '{"levels":{"1-1":{"completed":true,"bestScore":900,"bestTime":400.2},"1-2":{"completed":true,"bestScore":700,"bestTime":380},"1-3":{"completed":true,"bestScore":650,"bestTime":420.5},"1-4":{"completed":true,"bestScore":300,"bestTime":95.1}}}'
    ev(pg, f"localStorage.setItem('spiderman-game-campaign', '{old}')"); pg.reload(); pg.wait_for_timeout(500)
    t.check(badge(pg) == f"4/{total(pg)}", "old save badge 4/total")
    click(pg, '[data-action="campaign"]')
    t.check(ev(pg, "game.campaignWorldIndex") == 1, "old cleared save opens on world 2")
    t.check(tile_status(pg)[0] == "2-1:PLAY", "2-1 open for an old cleared save")
    click(pg, '.spiderman-game-world-tab[data-world="0"]')
    t.check(tile_status(pg)[0] == "1-1:CLEARED - 900", f"world 1 bests kept {tile_status(pg)[0]}")
    t.check(note(pg) == "World 1 cleared! WORLD 2 - OSCORP is open.", f"note {note(pg)}")
    # replaying the boss when world 2 is already open: flavour line, NEXT WORLD button
    click(pg, '[data-level="1-4"]')
    ev(pg, "game.level.boss.startDefeat()")
    for i in range(100):   # his defeat animation is counted in game frames: wait for the results, not a fixed time
        pg.wait_for_timeout(100)
        if state(pg) == "COMPLETE": break
    t.check(ev(pg, "document.querySelector('.spiderman-game-unlock-line').textContent") == "MYSTERIO'S SHOW IS OVER - EVERY STAGE OF WORLD 1 IS YOURS", "replay boss flavour line")
    t.check(ev(pg, "document.querySelector('.spiderman-game-next-button').style.display") == "", "NEXT WORLD still offered on replay")
    t.check(ev(pg, "game.getLevelProgress('1-4').bestScore") == 300 or ev(pg, "game.getLevelProgress('1-4').bestScore") > 300, "boss best kept")
    # normal stage clear in world 1 still says NEXT STAGE
    click(pg, '.spiderman-game-complete-menu [data-action="level-select"]')
    click(pg, '.spiderman-game-world-tab[data-world="0"]')
    click(pg, '[data-level="1-2"]')
    ev(pg, "(() => { var s = game.spiderman; var g = game.level.goal; s.x = g.x - 30; s.y = g.y - s.bodyHeight() - 2; })()")
    pg.wait_for_timeout(400)
    t.check(ev(pg, "document.querySelector('.spiderman-game-next-button').textContent") == "NEXT STAGE", "1-2 clear -> NEXT STAGE label")
    click(pg, '.spiderman-game-next-button')
    t.check(ev(pg, "game.level.id") == "1-3", "NEXT STAGE goes 1-2 -> 1-3")
    errs += errs2
    print("errors:", errs); t.check(not errs, "no browser errors")
    b.close()
t.report()
