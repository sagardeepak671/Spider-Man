from harness import *
t = T("2-1 -> 2-2 connection")
def flag(pg):
    ev(pg, "(() => { var s = game.spiderman, g = game.level.goal; s.x = g.x - 30; s.y = g.y - s.bodyHeight() - 2; s.invulnerableFrames = 999; })()")
    for i in range(30):
        pg.wait_for_timeout(100)
        if state(pg) == "COMPLETE": break
with sync_playwright() as p:
    b, pg, errs = open_page(p)
    ev(pg, "['1-1','1-2','1-3','1-4'].forEach(id => game.saveLevelProgress(id, {completed:true, score:1, time:1}))")
    pg.reload(); pg.wait_for_timeout(500)
    click(pg, '[data-action="campaign"]')
    t.check(ev(pg, "game.campaignWorldIndex") == 1, "level select opens on world 2")
    st = tile_status(pg)
    t.check(st == ["2-1:PLAY", "2-2:LOCKED:L", "2-3:LOCKED:L", "2-4:LOCKED:L"], f"2-1 open, 2-2 locked {st}")
    click(pg, '[data-level="2-2"]')
    t.check(state(pg) == "MENU" and note(pg) == "Stage 2-2 is locked. Clear stage 2-1 first.", f"locked 2-2 message: {note(pg)}")
    click(pg, '[data-level="2-1"]')
    t.check(ev(pg, "game.level.id") == "2-1" and ev(pg, "game.backdrop.theme") == "INDUSTRIAL", "2-1 starts (industrial)")
    flag(pg)
    t.check(state(pg) == "COMPLETE", "2-1 cleared at its flag")
    unlock = ev(pg, "document.querySelector('.spiderman-game-complete-menu .spiderman-game-unlock-line').textContent")
    nxt = ev(pg, "(b => b.style.display + '|' + b.textContent)(document.querySelector('.spiderman-game-next-button'))")
    t.check(unlock == "STAGE 2-2 UNLOCKED!", f"unlock line: {unlock}")
    t.check(nxt == "|NEXT STAGE", f"NEXT STAGE offered ({nxt})")
    click(pg, '.spiderman-game-complete-menu .spiderman-game-next-button')
    t.check(state(pg) == "PLAYING" and ev(pg, "game.level.id") == "2-2", "NEXT STAGE starts 2-2")
    t.check(ev(pg, "game.backdrop.theme") == "LAB" and ev(pg, "game.introFrames") > 0, "2-2 has its lab backdrop and the STAGE 2-2 intro card")
    t.check(ev(pg, "game.level.checkpoints.length") == 7 and ev(pg, "game.coins") == 0 and ev(pg, "game.spiderman.health") == 5, "fresh 2-2 start (no carry-over from 2-1)")
    pg.keyboard.press("Escape"); click(pg, '.spiderman-game-pause-menu [data-action="level-select"]')
    st = tile_status(pg)
    t.check(st[0].startswith("2-1:CLEARED") and st[1] == "2-2:PLAY" and st[2] == "2-3:LOCKED:L", f"tiles after 2-1 {st}")
    t.check(badge(pg) == f"5/{total(pg)}", f"badge 5/total ({badge(pg)})")
    click(pg, '[data-level="2-2"]')
    flag(pg)
    unlock = ev(pg, "document.querySelector('.spiderman-game-complete-menu .spiderman-game-unlock-line').textContent")
    t.check(unlock == "STAGE 2-3 UNLOCKED!" and ev(pg, "document.querySelector('.spiderman-game-next-button').style.display") == "", f"2-2 clear: {unlock}, NEXT STAGE offered")
    pg.reload(); pg.wait_for_timeout(500)
    t.check(badge(pg) == f"6/{total(pg)}", "badge 6/total after a refresh")
    click(pg, '[data-action="campaign"]')
    st = tile_status(pg)
    t.check(st[0].startswith("2-1:CLEARED") and st[1].startswith("2-2:CLEARED") and st[2] == "2-3:PLAY" and st[3] == "2-4:LOCKED:L", f"saved: {st}")
    # replaying 2-1 still links to 2-2 (already open: no unlock line)
    click(pg, '[data-level="2-1"]'); flag(pg)
    t.check(ev(pg, "document.querySelector('.spiderman-game-complete-menu .spiderman-game-unlock-line').style.display") == "none" and ev(pg, "document.querySelector('.spiderman-game-next-button').style.display") == "", "replaying 2-1: NEXT STAGE, no unlock line")
    click(pg, '.spiderman-game-complete-menu .spiderman-game-next-button')
    t.check(ev(pg, "game.level.id") == "2-2", "... and it leads to 2-2")
    print("errors:", errs); t.check(not errs, "no browser errors")
    b.close()
t.report()
