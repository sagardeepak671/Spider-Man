from harness import *
t = T("World 2 unlock / progress / level select")
with sync_playwright() as p:
    b, pg, errs = open_page(p)
    # ---- fresh save ----
    TOTAL = total(pg)
    t.check(badge(pg) == f"0/{TOTAL}", f"badge 0/{TOTAL} on fresh save ({badge(pg)})")
    click(pg, '[data-action="campaign"]')
    t.check(ev(pg, "game.campaignWorldIndex") == 0, "fresh save opens on world 1")
    tabs = ev(pg, "[...document.querySelectorAll('.spiderman-game-world-tab')].map(t=>t.textContent+'|'+t.className)")
    t.check(len(tabs) == 3, f"three world tabs {tabs}")
    t.check("is-current" in tabs[0] and "is-world-locked" in tabs[1] and "is-world-locked" in tabs[2], "tab 1 current, tabs 2 + 3 locked")
    st = tile_status(pg)
    t.check(st == ["1-1:PLAY", "1-2:LOCKED:L", "1-3:LOCKED:L", "1-4:LOCKED:L"], f"world 1 tiles {st}")
    t.check(ev(pg, "document.querySelector('.spiderman-game-level-tile.is-selected').getAttribute('data-level')") == "1-1", "1-1 preselected")
    # world 2 tab with the mouse
    click(pg, '.spiderman-game-world-tab[data-world="1"]')
    t.check(ev(pg, "game.campaignWorldIndex") == 1, "clicking tab 2 shows world 2")
    t.check("WORLD 2 - OSCORP" in ev(pg, "document.querySelector('.spiderman-game-world-title').textContent"), "world 2 title")
    st = tile_status(pg)
    t.check(st == ["2-1:LOCKED:L", "2-2:LOCKED:L", "2-3:LOCKED:L", "2-4:LOCKED:L"], f"world 2 all locked {st}")
    t.check(ev(pg, "document.querySelector('[data-level=\"2-4\"]').classList.contains('is-boss')"), "2-4 is a boss tile")
    t.check("GREEN GOBLIN" in ev(pg, "document.querySelector('[data-level=\"2-4\"]').textContent"), "boss tile says GREEN GOBLIN")
    t.check(note(pg) == "Defeat the World 1 boss to unlock World 2.", f"locked world note: {note(pg)}")
    click(pg, '[data-level="2-1"]')
    t.check(state(pg) == "MENU" and ev(pg, "game.level") is None, "locked 2-1 does not start")
    t.check("World 2 is locked" in note(pg) and "1-4" in note(pg), f"locked 2-1 message: {note(pg)}")
    # ---- clear 1-1..1-3: world 2 still locked ----
    ev(pg, "['1-1','1-2','1-3'].forEach(id => game.saveLevelProgress(id, {completed:true, score:100, time:60}))")
    ev(pg, "game.showMainMenu(); game.handleMenuAction('campaign')")
    t.check(ev(pg, "game.campaignWorldIndex") == 0, "still opens on world 1 before the boss")
    t.check(tile_status(pg)[3] == "1-4:PLAY", "boss playable after 1-3")
    t.check(ev(pg, "game.isLevelUnlocked('2-1')") is False, "2-1 locked before the boss")
    # ---- beat Mysterio through the real stage-clear path ----
    click(pg, '[data-level="1-4"]')
    t.check(state(pg) == "PLAYING" and ev(pg, "game.level.id") == "1-4", "boss stage starts from the tile")
    ev(pg, "game.level.boss.startDefeat()")
    for i in range(60):
        pg.wait_for_timeout(200)
        if state(pg) != "PLAYING": break
    print("   boss defeat took", ev(pg, "game.levelFrames"), "frames into the stage")
    t.check(state(pg) == "COMPLETE", f"boss defeat completes the stage ({state(pg)})")
    title = ev(pg, "document.querySelector('.spiderman-game-complete-menu .spiderman-game-panel-title').textContent")
    unlock = ev(pg, "document.querySelector('.spiderman-game-complete-menu .spiderman-game-unlock-line').textContent")
    nxt = ev(pg, "(b => b.style.display + '|' + b.textContent)(document.querySelector('.spiderman-game-next-button'))")
    t.check(title == "WORLD 1 CLEARED!", f"title {title}")
    t.check(unlock == "WORLD 2 - OSCORP UNLOCKED!", f"unlock line {unlock}")
    t.check(nxt == "|NEXT WORLD", f"next button visible + NEXT WORLD ({nxt})")
    t.check(ev(pg, "game.isLevelUnlocked('2-1')") is True and ev(pg, "game.isLevelUnlocked('2-2')") is False, "2-1 open, 2-2 locked")
    saved = ev(pg, "JSON.parse(localStorage.getItem('spiderman-game-campaign')).levels['1-4']")
    t.check(saved and saved["completed"], f"1-4 saved {saved}")
    # NEXT WORLD -> 2-1
    click(pg, '.spiderman-game-complete-menu .spiderman-game-next-button')
    t.check(state(pg) == "PLAYING" and ev(pg, "game.level.id") == "2-1", "NEXT WORLD starts 2-1")
    t.check(ev(pg, "game.backdrop.theme") == "INDUSTRIAL" and ev(pg, "game.mode") == "CAMPAIGN", "2-1 campaign mode / industrial backdrop")
    # pause -> level select opens on world 2
    pg.keyboard.press("Escape"); pg.wait_for_timeout(150)
    t.check(state(pg) == "PAUSED", "Esc pauses 2-1")
    t.check("STAGE 2-1" in ev(pg, "document.querySelector('.spiderman-game-pause-menu').textContent"), "pause shows STAGE 2-1")
    click(pg, '.spiderman-game-pause-menu [data-action="level-select"]')
    t.check(ev(pg, "game.campaignWorldIndex") == 1, "level select from 2-1 opens on world 2")
    st = tile_status(pg)
    t.check(st == ["2-1:PLAY", "2-2:LOCKED:L", "2-3:LOCKED:L", "2-4:LOCKED:L"], f"world 2 tiles after boss {st}")
    tabs = ev(pg, "[...document.querySelectorAll('.spiderman-game-world-tab')].map(t=>t.className)")
    t.check("is-world-cleared" in tabs[0] and "is-world-locked" not in tabs[1], f"tab states {tabs}")
    t.check(badge(pg) == f"4/{TOTAL}", f"badge 4/{TOTAL} ({badge(pg)})")
    # ---- refresh: progress kept, world 2 default ----
    pg.reload(); pg.wait_for_timeout(500)
    t.check(badge(pg) == f"4/{TOTAL}", "badge kept after refresh")
    click(pg, '[data-action="campaign"]')
    t.check(ev(pg, "game.campaignWorldIndex") == 1, "after refresh opens on world 2 (latest unlocked)")
    t.check(ev(pg, "document.querySelector('.spiderman-game-level-tile.is-selected').getAttribute('data-level')") == "2-1", "2-1 preselected")
    # ---- clear 2-1 through the goal flag ----
    click(pg, '[data-level="2-1"]')
    ev(pg, "(() => { var s = game.spiderman; var g = game.level.goal; s.x = g.x - 30; s.y = g.y - s.bodyHeight() - 2; })()")
    pg.wait_for_timeout(400)
    t.check(state(pg) == "COMPLETE", "touching the 2-1 flag clears it")
    title = ev(pg, "document.querySelector('.spiderman-game-complete-menu .spiderman-game-panel-title').textContent")
    unlock = ev(pg, "document.querySelector('.spiderman-game-complete-menu .spiderman-game-unlock-line').textContent")
    t.check(title == "STAGE CLEAR!", f"2-1 title {title}")
    t.check(unlock == "STAGE 2-2 UNLOCKED!", f"2-1 unlock line {unlock}")
    t.check(ev(pg, "document.querySelector('.spiderman-game-next-button').style.display") == "", "NEXT STAGE offered (2-2 is built)")
    click(pg, '.spiderman-game-complete-menu [data-action="level-select"]')
    st = tile_status(pg)
    t.check(st[0].startswith("2-1:CLEARED") and st[1] == "2-2:PLAY" and st[2] == "2-3:LOCKED:L", f"tiles after 2-1 {st}")
    click(pg, '[data-level="2-3"]')
    t.check(state(pg) == "MENU" and "locked" in note(pg), "2-3 still locked")
    # replaying 2-1 with a worse result keeps the best
    best = ev(pg, "game.getLevelProgress('2-1')")
    ev(pg, "game.saveLevelProgress('2-1', {completed:true, score:0, time:9999})")
    best2 = ev(pg, "game.getLevelProgress('2-1')")
    t.check(best2["bestScore"] == best["bestScore"] and best2["bestTime"] == best["bestTime"], "best score / time never get worse")
    pg.reload(); pg.wait_for_timeout(500)
    t.check(badge(pg) == f"5/{TOTAL}", f"badge 5/{TOTAL} after refresh ({badge(pg)})")
    t.check(ev(pg, "game.isLevelCompleted('2-1') && game.isLevelUnlocked('2-2') && !game.isLevelUnlocked('2-3')"), "2-1 clear kept after refresh")
    # ---- keyboard navigation of the tabs ----
    click(pg, '[data-action="campaign"]')
    # buttons: tab1 tab2 tab3 tiles(4) reset back ; move to tab 1 with Up from 2-2 (index 4)
    for _ in range(4): pg.keyboard.press("ArrowUp")
    sel = ev(pg, "document.querySelector('.spiderman-game-campaign-panel .is-selected').textContent")
    t.check(sel == "WORLD 1", f"keyboard reaches the tab ({sel})")
    pg.keyboard.press("Enter"); pg.wait_for_timeout(100)
    t.check(ev(pg, "game.campaignWorldIndex") == 0 and tile_status(pg)[0].startswith("1-1"), "Enter on a tab switches world")
    pg.keyboard.press("ArrowRight"); pg.keyboard.press("Enter"); pg.wait_for_timeout(100)
    t.check(ev(pg, "game.campaignWorldIndex") == 1, "Right + Enter goes to world 2")
    pg.keyboard.press("Escape"); pg.wait_for_timeout(100)
    t.check(ev(pg, "game.openPanel") is None, "Esc closes the panel")
    # ---- reset progress ----
    click(pg, '[data-action="campaign"]')
    click(pg, '.spiderman-game-campaign-panel [data-action="reset-progress"]')
    click(pg, '.spiderman-game-campaign-panel [data-action="reset-progress"]')
    t.check(ev(pg, "game.campaignWorldIndex") == 0, "reset goes back to world 1")
    t.check(tile_status(pg)[0] == "1-1:PLAY" and ev(pg, "game.isLevelUnlocked('2-1')") is False, "reset locks world 2 again")
    t.check(badge(pg) == f"0/{TOTAL}", f"badge 0/{TOTAL} after reset")
    t.check(ev(pg, "localStorage.getItem('spiderman-game-campaign')") == '{"levels":{}}', "storage emptied")
    print("errors:", errs); t.check(not errs, "no browser errors")
    b.close()
t.report()
